/**
 * Get a random quote excluding specified indices
 * Used for quote rotation without repeats
 */
export function getRandomQuoteExcluding(excludeIds: string[] = []): StudyWisdom {
  const availableQuotes = studyWisdomQuotes.filter(q => !excludeIds.includes(q.id));
  const randomIndex = Math.floor(Math.random() * availableQuotes.length);
  return availableQuotes[randomIndex];
}

/**
 * Get quote by ID
 */
export function getQuoteById(id: string): StudyWisdom | undefined {
  return studyWisdomQuotes.find(q => q.id === id);
}

/**
 * Get all unique categories
 */
export function getCategories(): string[] {
  const categories = new Set(studyWisdomQuotes.map(q => q.category));
  return Array.from(categories).sort();
}

/**
 * Get all unique authors
 */
export function getAuthors(): string[] {
  const authors = new Set(studyWisdomQuotes.map(q => q.author));
  return Array.from(authors).sort();
}
